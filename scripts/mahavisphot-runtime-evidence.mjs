function pushCheck(id, ok, details = {}) {
  checks.push({
    id,
    status: ok ? "passed" : "failed",
    details,
  });
}

function requireCheck(id, ok, details = {}) {
  pushCheck(id, ok, details);
  if (!ok) {
    const message = details.message || `Runtime evidence check failed: ${id}`;
    throw new Error(message);
  }
}

function recordBlocked(capability, reason, requiredEvidence) {
  blocked.push({
    capability,
    status: "blocked",
    reason,
    requiredEvidence,
  });
}

function cookieFromHeader(setCookie) {
  if (!setCookie) return "";
  return String(setCookie)
    .split(";")
    .slice(0, 1)
    .join(";")
    .trim();
}

async function httpRequest(baseUrl, route, options = {}) {
  const url = new URL(route, baseUrl);
  const headers = { ...(options.headers || {}) };
  if (options.jsonBody !== undefined) {
    headers["Content-Type"] = "application/json";
    options.body = JSON.stringify(options.jsonBody);
  }
  if (options.withCookie && cookieJar) {
    headers.Cookie = cookieJar;
  }
  const started = performance.now();
  const response = await fetch(url, {
    method: options.method || "GET",
    headers,
    body: options.body,
  });
  const text = await response.text();
  const setCookie = response.headers.get("set-cookie");
  if (options.captureCookie && setCookie) {
    cookieJar = cookieFromHeader(setCookie);
  }
  let json = null;
  if ((response.headers.get("content-type") || "").includes("application/json")) {
    json = JSON.parse(text);
  }
  return {
    route,
    status: response.status,
    ok: response.ok,
    durationMs: Number((performance.now() - started).toFixed(3)),
    contentType: response.headers.get("content-type") || "",
    text,
    json,
  };
}

function containsAll(text, values) {
  return values.every((value) => text.includes(value));
}

async function fileExistsFromAssetUrl(assetUrl) {
  if (typeof assetUrl !== "string" || !assetUrl.startsWith("/assets/")) return false;
  const relativePath = assetUrl.slice("/assets/".length);
  const filePath = path.join(root, relativePath);
  const fileStat = await stat(filePath);
  return fileStat.isFile() && fileStat.size > 0;
}

async function readJsonFromAssetUrl(assetUrl) {
  if (typeof assetUrl !== "string" || !assetUrl.startsWith("/assets/")) return null;
  const relativePath = assetUrl.slice("/assets/".length);
  const filePath = path.join(root, relativePath);
  return JSON.parse(await readFile(filePath, "utf8"));
}

function evidenceMarkdown(evidence) {
  const rows = evidence.checks
    .map((check) => `| ${check.id} | ${check.status} | ${JSON.stringify(check.details).replace(/\|/g, "\\|")} |`)
    .join("\n");
  const blockerRows = evidence.blockedCapabilities
    .map((item) => `| ${item.capability} | ${item.status} | ${item.reason} | ${item.requiredEvidence} |`)
    .join("\n");
  return `# Mahavisphot Runtime Evidence

Generated by \`npm run mahavisphot:evidence\`.

- Run ID: \`${evidence.runId}\`
- Started at: \`${evidence.startedAt}\`
- Completed at: \`${evidence.completedAt}\`
- Base URL: \`${evidence.baseUrl}\`
- Evidence JSON: \`docs/mahavisphot/evidence/latest-runtime-evidence.json\`
- Overall status: \`${evidence.overallStatus}\`

## Verified Runtime Checks

| Check | Status | Details |
| --- | --- | --- |
${rows}

## Blocked Capabilities

These capabilities remain blocked because this run did not verify their required runtime integrations.

| Capability | Status | Reason | Required Evidence |
| --- | --- | --- | --- |
${blockerRows}

PRODUCTION_READY=false
PHKD_VERDICT=BLOCKED_UNTIL_RUNTIME_EVIDENCE
`;
}

